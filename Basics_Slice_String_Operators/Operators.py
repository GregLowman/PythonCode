b = 3

print(a+b)
print(a-b)
print(a*b)
print(a / b)
print(a//b)
print(a % b)

print()

for i in range(1, 4):
    print(i)

print(a + b / 3 - 4 * 12)
print(a + (b / 3) - (4 * 12))

